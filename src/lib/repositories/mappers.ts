/**
 * Db → App Model Mappers (Phase 13)
 * ==================================
 * Pure functions mapping database rows (`Db*` from `@/lib/supabase/types`)
 * onto the application types (`@/types/*`). Mappers are defensive: nullable
 * columns receive demo-safe defaults and `unknown` JSON columns are validated
 * before being cast, so the rest of the app can trust the resulting types.
 *
 * These are plain functions with no I/O — safe to import from API routes,
 * server components, and tests.
 */

